# fields.py <eboot.elf> <funcinfo.tsv> <out.md> : reflected field names + offsets per reflect function.
# Scans every bl to Reflect_AddField 0x815ba3d4 / Reflect_FillRecord 0x812414ea / Reflect_FillRecordEx 0x81241548;
# r1 = name string, r2 = object register + offset, r3 = type code.
import sys, struct, re, capstone
BASE, HDR = 0x81000000, 0x80
T = {0x815ba3d4: "", 0x812414ea: "", 0x81241548: ""}
f = open(sys.argv[1], "rb").read()
md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_THUMB); md.skipdata = True
def cstr(va):
    o = va - BASE + HDR
    if o < 0 or o >= len(f): return None
    e = f.find(b"\0", o, o + 96)
    s = f[o:e]
    if e < 0 or not s or any(c < 0x20 or c > 0x7e for c in s): return None
    return s.decode()
funcs = []
for l in open(sys.argv[2], encoding="utf-8"):
    p = l.split()
    if p and p[0] == "F": funcs.append((int(p[1], 16), p[2], int(p[-1])))
out = []; nf = nfl = 0
num = lambda t: int(t.lstrip("#"), 0)
for a, name, size in funcs:
    blob = f[a - BASE + HDR:a - BASE + HDR + size]
    if size < 12: continue
    const = {}; off = {}; rows = []
    for i in md.disasm(blob, a):
        m, ops = i.mnemonic, [x.strip() for x in i.op_str.split(",")]
        d = ops[0] if ops else ""
        try:
            if m.startswith("movt"):
                const[d] = (const.get(d, 0) & 0xffff) | (num(ops[1]) << 16)
            elif m.startswith("movw") or (m.startswith("mov") and len(ops) == 2 and ops[1].startswith("#")):
                const[d] = num(ops[1]) & 0xffffffff; off.pop(d, None)
            elif m.startswith("movt"):
                const[d] = (const.get(d, 0) & 0xffff) | (num(ops[1]) << 16)
            elif m.startswith("add") and len(ops) == 3 and ops[2].startswith("#"):
                b0, o0 = off.get(ops[1], (ops[1], 0)); off[d] = (b0, o0 + num(ops[2])); const.pop(d, None)
            elif m.startswith("add") and len(ops) == 2 and ops[1].startswith("#"):
                b, o = off.get(d, (d, 0)); off[d] = (b, o + num(ops[1])); const.pop(d, None)
            elif m.startswith("mov") and len(ops) == 2:
                if ops[1] in const: const[d] = const[ops[1]]
                else: const.pop(d, None)
                off[d] = off.get(ops[1], (ops[1], 0))
            elif m in ("bl", "blx"):
                t = num(ops[0]) if ops[0].startswith("#") else 0
                if t in T:
                    s = cstr(const.get("r1", 0))
                    b, o = off.get("r2", ("?", 0))
                    rows.append((o, s or "(computed name)", const.get("r3", -1), i.address))
                for r in ("r0", "r1", "r2", "r3"): const.pop(r, None); off.pop(r, None)
            elif d in const or d in off:
                if not m.startswith(("cmp", "tst", "str", "push", "b", "cb", "it")): const.pop(d, None); off.pop(d, None)
        except (ValueError, IndexError):
            pass
    if rows and any(r[1] != "(computed name)" for r in rows):  # all-computed = forwarding helper, not a struct
        nf += 1; nfl += len(rows)
        out.append("## %s 0x%08x\n" % (name, a))
        out += ["- +0x%x %s (type 0x%x)\n" % (o, s, t & 0xff) if t >= 0 else "- +0x%x %s\n" % (o, s) for o, s, t, _ in rows]
        out.append("\n")
head = "# Reflected fields\nGenerated by tools/fields.py. %d functions, %d fields. Offsets are relative to the object pointer of the reflect function; an offset of 0 can also mean the scanner lost track.\n\n" % (nf, nfl)
open(sys.argv[3], "w", encoding="utf-8", newline="\n").write(head + "".join(out))
print("functions", nf, "fields", nfl)
